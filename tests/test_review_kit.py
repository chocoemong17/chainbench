def test_subprocess_failure_does_not_expose_local_paths(monkeypatch, tmp_path):
    monkeypatch.setattr(review.subprocess, "run", lambda *a, **k:
                        SimpleNamespace(returncode=1, stdout="/home/private/person", stderr="secret"))
    with pytest.raises(review.ReviewError) as exc:
        review.command(["-m", "chainbench"], tmp_path)
    assert "private" not in str(exc.value) and "secret" not in str(exc.value)


def test_process_is_isolated_bounded_and_no_shell(monkeypatch, tmp_path):
    seen = {}

    def fake(args, **kwargs):
        seen.update(args=args, kwargs=kwargs)
        return SimpleNamespace(returncode=0, stdout="{}", stderr="")

    monkeypatch.setattr(review.subprocess, "run", fake)
    review.command(["-m", "chainbench"], tmp_path)
    assert seen["args"][1] == "-I"
    assert seen["kwargs"]["timeout"] == 60
    assert not seen["kwargs"].get("shell", False)


