def test_compressed_reference_and_plain_input_equivalent(tmp_path, bundle):
    plain, zipped = tmp_path / "plain.json", tmp_path / "compressed.json.gz"
    raw = json.dumps(bundle).encode()
    plain.write_bytes(raw)
    zipped.write_bytes(gzip.compress(raw, mtime=0))
    assert review.load(plain) == review.load(zipped)


def test_bounded_gzip_expansion(tmp_path):
    p = tmp_path / "big.json.gz"
    p.write_bytes(gzip.compress(b" " * (review.MAX_BYTES + 1), mtime=0))
    with pytest.raises(review.ReviewError):
        review.load(p)


