def test_compare_cli_exit_codes(tmp_path, bundle, base_bundle):
    left, right = tmp_path / "left.json", tmp_path / "right.json"
    review.write_new(left, base_bundle)
    review.write_new(right, bundle)
    assert review.main(["compare", str(left), str(right)]) == 0
    bundle["experiments"]["simplex"]["fixture"]["input_sha256"] = "1" * 64
    right.write_text(json.dumps(bundle))
    assert review.main(["compare", str(left), str(right)]) == 3
    bundle["experiments"]["simplex"]["runs"][0]["rows"][1]["gap"] += .1
    right.write_text(json.dumps(bundle))
    assert review.main(["compare", str(left), str(right)]) == 1
    right.write_text("{}")
    assert review.main(["compare", str(left), str(right)]) == 2


